/** Сообщения для HR: без путей к файлам и жаргона разработчиков. */

const RULES = [
  [/не найдено резюме/i, 'По этой фразе на hh.ru не нашлось резюме. Попробуйте другие слова: должность и навыки.'],
  [/токен|переавториз|token\.json/i, 'Нужно обновить доступ к hh.ru. Обратитесь к администратору.'],
  [/403|forbidden/i, 'Не удалось открыть вакансию. Проверьте ссылку и что это ваша вакансия на hh.ru.'],
  [/404/i, 'Вакансия не найдена на hh.ru — возможно, снята с публикации.'],
  [/429|лимит/i, 'Слишком много запросов к hh.ru. Подождите 10–15 минут и попробуйте снова.'],
  [/resumes_camp_|нет файла резюме|\.json/i, 'Резюме не сохранились с hh.ru. Запустите подбор заново.'],
  [/перезапуск|uvicorn|api/i, 'Запустите подбор ещё раз. Если не поможет — администратор.'],
]

export function friendlyError(message) {
  if (!message) return ''
  let text = String(message)
  for (const [re, repl] of RULES) {
    if (re.test(text)) return repl
  }
  if (text.length > 200) text = `${text.slice(0, 200)}…`
  return text
}
