import re

NOISE_PATTERNS = [
    # О нас / О компании
    r"\bо\s+нас\b.*?(?=(требования|задачи|ждем|наш\s+кандидат|$))",
    r"\bо\s+компании\b.*?(?=(требования|задачи|ждем|наш\s+кандидат|$))",
    r"\bо\s+компании[-\s]*заказчике\b.*?(?=(требования|задачи|ждем|наш\s+кандидат|$))",

    # Условия и бенефиты
    r"\bчто\s+предлагаем\b.*",
    r"\bчто\s+мы\s+предлагаем\b.*",
    r"\bусловия\s+работы\b.*",
    r"\bпреимущества\s+работы\b.*",
    r"\bпреимущества\b.*?(?=(требования|задачи|ждем|$))",
    r"\bмы\s+предлагаем\b.*",
    r"\bкомпенсация\b.*",
    r"\bдмс\b.*",
    r"\bзоны\s+отдыха\b.*",
    r"\bкорпоратив\b.*",
    r"\bкарьерн\w*\s+рост\b.*",
    r"\bтаймтрекер\b.*",
    r"\bбольничн\w*\b.*",
    r"\bотпуск\w*\b.*",
    r"\bсвободн\w*\s+график\b.*",
    r"\bофис\w*\b.*",
    r"\bспокойн\w*\s+ритм\b.*",
    r"\bтворческ\w*\s+атмосфер\w*\b.*",
    r"\bкомфортн\w*\b.*",
    r"\bбесплатн\w*\s+кофе\b.*",

    # Этапы отбора / интервью / дружба / знакомство
    r"\bэтапы\s+отбора\b.*",
    r"\bкак\s+проходит\s+процесс\b.*",
    r"\bкоротк\w*\s+знакомств\w*\b.*",
    r"\bтестов\w*\s+задани\w*\b.*",
    r"\bсобеседовани\w*\b.*",
    r"\bподружимс\w*\b.*",
    r"\bподружимся\b.*",
    r"\bдобро\s+пожаловать\b.*",
    r"\bстань\s+частью\s+команды\b.*",
]

def remove_noise_requirements(text: str) -> str:
    if not text:
        return ""
    cleaned = text.lower()
    for pattern in NOISE_PATTERNS:
        cleaned = re.sub(pattern, " ", cleaned, flags=re.IGNORECASE | re.DOTALL)
    cleaned = re.sub(r"\s+", " ", cleaned).strip()
    return cleaned
